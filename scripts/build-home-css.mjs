import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sources = [
  'styles/tokens.css',
  'styles/foundations.css',
  'styles/components.css',
  'styles/motion.css',
  'brand/visual-art-ai-design-system.css',
  'styles/home-v11.css',
  'styles/home-clarity.css',
];
const parts = await Promise.all(sources.map(async source => {
  const css = await readFile(resolve(root, 'site', source), 'utf8');
  if (/@import\b|url\(/i.test(css)) throw new Error('Nested import or relative URL needs resolution in ' + source);
  return '/* Source: ' + source + ' */\n' + css.trim();
}));
await writeFile(resolve(root, 'site/home-core.css'), '/* Generated by node scripts/build-home-css.mjs. Edit the source files. */\n' + parts.join('\n\n') + '\n');
console.log('Homepage CSS generated from ' + sources.length + ' sources.');
